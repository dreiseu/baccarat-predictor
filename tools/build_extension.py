"""Build the Chrome side-panel extension from prototype/shoe-odds.html.

Usage: python3 tools/build_extension.py

The prototype stays the single source. Extension pages can't run inline
scripts, so the script is written to its own file, and Google Fonts are
dropped so the panel works offline with no outside requests.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'prototype' / 'shoe-odds.html'
OUT = ROOT / 'extension'


def main():
    src = SRC.read_text(encoding='utf-8')
    title = re.search(r'<title>(.*?)</title>', src).group(1)
    style = re.search(r'<style>(.*?)</style>', src, re.S).group(1)
    body = src[src.index('</style>') + len('</style>'):src.index('<script>')].strip()
    script = re.search(r'<script>(.*?)</script>', src, re.S).group(1).strip()

    html = f'''<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<style>
body {{ margin: 0; }}
img {{ max-width: 100%; }}
{style.strip()}
</style>
</head>
<body>
{body}
<script src="sidepanel.js"></script>
</body>
</html>
'''
    (OUT / 'sidepanel.html').write_text(html, encoding='utf-8')
    (OUT / 'sidepanel.js').write_text('// Generated by tools/build_extension.py from prototype/shoe-odds.html. Edit the prototype, then rebuild.\n' + script + '\n', encoding='utf-8')
    print(f'Wrote {OUT / "sidepanel.html"} and {OUT / "sidepanel.js"}')


if __name__ == '__main__':
    main()
